#!/usr/bin/env node
// Generates deploy/Caddyfile and deploy/ecosystem.config.cjs from apps.json
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { site, apps } = JSON.parse(readFileSync(join(root, "apps.json"), "utf8"));
const deployable = apps.filter((a) => a.status !== "planned");
mkdirSync(join(root, "deploy"), { recursive: true });

const proxy = (a) =>
  a.type === "static"
    ? `root * ${site.appsRoot}/${a.slug}/${a.dist ?? "dist"}\n\ttry_files {path} /index.html\n\tfile_server`
    : `reverse_proxy 127.0.0.1:${a.port}`;

const hub = `\troot * ${site.hubRoot}/dist
\tencode zstd gzip
\theader {
\t\tX-Content-Type-Options nosniff
\t\tReferrer-Policy strict-origin-when-cross-origin
\t\tX-Frame-Options SAMEORIGIN
\t}
\t@assets path /assets/*
\theader @assets Cache-Control "public, max-age=31536000, immutable"`;

let out = `# AUTO-GENERATED by scripts/generate.mjs — edit apps.json instead.\n\n`;

if (site.routing === "path") {
  out += `${site.domain} {\n${hub}\n`;
  for (const a of deployable) {
    // handle_path strips the prefix; apps must work when served from /apps/<slug>/
    out += `\n\thandle_path /apps/${a.slug}/* {\n\t\t${proxy(a).replaceAll("\n\t", "\n\t\t")}\n\t}\n`;
  }
  out += `\n\thandle {\n\t\ttry_files {path} /index.html\n\t\tfile_server\n\t}\n}\n`;
} else {
  out += `${site.domain}, www.${site.domain} {\n${hub}\n\ttry_files {path} /index.html\n\tfile_server\n}\n`;
  for (const a of deployable) {
    out += `\n${a.slug}.${site.domain} {\n\tencode zstd gzip\n\t${proxy(a)}\n}\n`;
  }
}
writeFileSync(join(root, "deploy/Caddyfile"), out);

const procs = deployable
  .filter((a) => a.type === "node")
  .map((a) => ({
    name: `app-${a.slug}`,
    cwd: `${site.appsRoot}/${a.slug}`,
    script: "/bin/bash",
    args: ["-lc", a.start ?? "npm run start"],
    env: { NODE_ENV: "production", PORT: String(a.port), HOST: "127.0.0.1" },
    max_memory_restart: "512M",
    autorestart: true,
  }));
writeFileSync(
  join(root, "deploy/ecosystem.config.cjs"),
  `// AUTO-GENERATED by scripts/generate.mjs — edit apps.json instead.\nmodule.exports = ${JSON.stringify({ apps: procs }, null, 2)};\n`,
);
console.log(`Generated Caddyfile (${site.routing} mode) + pm2 config for ${procs.length} node app(s), ${deployable.length - procs.length} static.`);
